/** Yeni parçaları bölüme ekler: sona (çıkış taşınır) ya da finalden önceye. */
function extend(l: LevelDef) {
  const ext = EXTENSIONS[l.id]
  if (!ext) return
  const d = 20 - ext.base
  const parts = ext.chunks.map((c) => {
    const rows = chunk(c)
    // tabanı yukarı kaydır: alttaki satır tekrar eder (çukur çukur, zemin zemin kalır)
    return d > 0 ? [...rows.slice(d), ...Array.from({ length: d }, () => rows[rows.length - 1])] : rows
  })
  const add = join(...parts)
  if (ext.mode === 'append') {
    const base = l.map.map((r) => r.replace('E', ' '))
    l.map = base.map((r, y) => r + add[y])
  } else {
    const at = ext.at ?? l.map[0].length
    // araya giren parçanın çıkışı olmaz: bölümün finali yerinde kalır
    l.map = l.map.map((r, y) => r.slice(0, at) + add[y].replace('E', ' ') + r.slice(at))
  }
  l.hints = [...l.hints, ...ext.hints]
  l.medals = l.medals.map((m) => m + ext.medal) as [number, number, number]
}

/** İmza bölümü: şehrin bir köşesini anlatan parça, verilen sütuna eklenir; tabela ipucu ve şehir insanı sırasına oturur. */
function addSignature(l: LevelDef) {
  const sig = SIGNATURES[l.id]
  if (!sig) return
  const count = (ch: string) => l.map.reduce((n, r) => n + [...r.slice(0, sig.at)].filter((c) => c === ch).length, 0)
  const signs = count('?')
  const people = count('n')
  l.map = l.map.map((r, y) => r.slice(0, sig.at) + sig.rows[y] + r.slice(sig.at))
  l.hints = [...l.hints.slice(0, signs), ...sig.hints, ...l.hints.slice(signs)]
  l.npcs = [...l.npcs.slice(0, people), ...sig.npcs, ...l.npcs.slice(people)]
  sig.hintAt = signs
  sig.npcAt = people
  l.medals = l.medals.map((m) => m + sig.medal) as [number, number, number]
}

for (const l of LEVELS) {
  extend(l)
  addSignature(l)
  l.map = enrich(l.map, l.city)
}

